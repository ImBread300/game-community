const guideImageBase = new URL('../images/', document.currentScript.src);
const guideModal = document.querySelector('#guideModal');
if (guideModal) {
  const body = guideModal.querySelector('[data-guide-body]');
  const heading = guideModal.querySelector('#guideModalTitle');
  const element = (tag, className, text) => {
    const node = document.createElement(tag);
    node.className = className;
    if (text) node.textContent = text;
    return node;
  };
  guideModal.addEventListener('show.bs.modal', (event) => {
    const slug = event.relatedTarget?.dataset.guide;
    const guide = communityGuides[slug];
    if (!guide) { event.preventDefault(); return; }
    heading.textContent = guide.title;
    const hero = element('div', 'guide-reader-hero');
    const cover = element('img', 'guide-reader-cover');
    cover.src = new URL(`guides/${slug}.jpg`, guideImageBase).href;
    cover.alt = `Обложка руководства по ${guide.game}`;
    cover.width = 128; cover.height = 128;
    const intro = element('div', 'p-4');
    intro.append(element('p', 'eyebrow', `${guide.game} · Основы игры`), element('p', 'text-body-secondary mb-0', guide.summary));
    hero.append(cover, intro);
    const layout = element('div', 'guide-reader-layout');
    const contents = element('nav', 'guide-reader-toc');
    contents.setAttribute('aria-label', 'Оглавление руководства');
    contents.append(element('h3', 'h6', 'Содержание'));
    const article = element('article', 'guide-reader-content');
    guide.sections.forEach(([title, paragraphs], index) => {
      const section = element('section', 'guide-reader-section');
      section.id = `guide-section-${index}`;
      section.setAttribute('aria-labelledby', `guide-heading-${index}`);
      const sectionHeading = element('h3', 'h4 mb-3', title);
      sectionHeading.id = `guide-heading-${index}`;
      section.append(sectionHeading);
      paragraphs.forEach(text => section.append(element('p', 'text-body-secondary', text)));
      article.append(section);
      const button = element('button', 'guide-toc-link', `${index + 1}. ${title}`);
      button.type = 'button';
      button.setAttribute('aria-controls', section.id);
      button.addEventListener('click', () => {
        const top = section.getBoundingClientRect().top - body.getBoundingClientRect().top + body.scrollTop - 24;
        body.scrollTo({ top, behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'instant' : 'smooth' });
      });
      contents.append(button);
    });
    layout.append(contents, article);
    body.replaceChildren(hero, layout);
    body.scrollTop = 0;
    updateContents();
  });
  function updateContents() {
    const sections = [...body.querySelectorAll('.guide-reader-section')];
    const top = body.getBoundingClientRect().top + 48;
    let active = 0;
    sections.forEach((section, index) => { if (section.getBoundingClientRect().top <= top) active = index; });
    if (body.scrollTop > 0 && body.scrollHeight - body.scrollTop - body.clientHeight <= 2) active = sections.length - 1;
    body.querySelectorAll('.guide-toc-link').forEach((button, index) => {
      button.classList.toggle('active', index === active);
      if (index === active) button.setAttribute('aria-current', 'true');
      else button.removeAttribute('aria-current');
    });
  }
  body.addEventListener('scroll', updateContents, { passive: true });
  guideModal.addEventListener('shown.bs.modal', () => {
    heading.focus({ preventScroll: true });
    updateContents();
  });
}
